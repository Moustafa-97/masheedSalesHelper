import { Injectable } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { randomUUID } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { mkdir, stat, writeFile } from 'node:fs/promises';
import { dirname, extname, isAbsolute, join, normalize, resolve, sep } from 'node:path';
import type { Readable } from 'node:stream';

/** Where uploaded bytes live. Local folder for now; an S3-compatible store can implement the same three calls. */
export abstract class FileStorage {
  abstract put(buffer: Buffer, originalName: string): Promise<string>;
  abstract read(key: string): Promise<Readable>;
  abstract exists(key: string): Promise<boolean>;
}

/** Files in UPLOAD_DIR (default ./uploads next to the API), under year/month folders. */
@Injectable()
export class LocalFileStorage extends FileStorage {
  private readonly root: string;

  constructor(config: ConfigService) {
    super();
    const dir = config.get<string>('UPLOAD_DIR') ?? 'uploads';
    this.root = isAbsolute(dir) ? dir : resolve(process.cwd(), dir);
  }

  async put(buffer: Buffer, originalName: string) {
    const now = new Date();
    const ext = extname(originalName).toLowerCase().replace(/[^.a-z0-9]/g, '').slice(0, 10);
    const key = `${now.getUTCFullYear()}/${String(now.getUTCMonth() + 1).padStart(2, '0')}/${randomUUID()}${ext}`;
    const path = this.path(key);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, buffer, { flag: 'wx' });
    return key;
  }

  async read(key: string) {
    return createReadStream(this.path(key));
  }

  async exists(key: string) {
    return stat(this.path(key)).then(
      (s) => s.isFile(),
      () => false,
    );
  }

  /** Keys are generated by put(), but refuse anything that would leave the root anyway. */
  private path(key: string) {
    const full = normalize(join(this.root, key));
    if (!full.startsWith(this.root + sep)) throw new Error('Invalid storage key');
    return full;
  }
}

export const ALLOWED_MIME_TYPES = new Set([
  'application/pdf',
  'image/jpeg',
  'image/png',
  'image/webp',
  'image/heic',
  'image/heif',
  'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  'application/vnd.ms-excel',
  'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  'application/msword',
]);

export const MAX_UPLOAD_BYTES = 20 * 1024 * 1024;
